import { EMBEDDING_MODEL, TOP_K } from "./config.ts";
import type { Question, Summary } from "./types.ts";

type Ranks = Record<string, (number | undefined)[]>;

/** RESULTS.md: one summary table, then the rank of the first relevant chunk per question. */
export function renderReport(summaries: Summary[], ranks: Ranks, questions: Question[]): string {
  const best = [...summaries].sort((a, b) => b.mrr - a.mrr || b.hit1 - a.hit1 || a.chunks - b.chunks)[0]!;
  const names = summaries.map((s) => s.name);
  const f2 = (n: number) => n.toFixed(2);

  const summaryRows = summaries.map(
    (s) =>
      `| ${s.name} | ${s.chunks} | ${s.avgChars} | ${f2(s.hit1)} | ${f2(s.hit3)} | ${f2(s.hit5)} | ${s.mrr.toFixed(3)} | ${f2(s.sourceHit1)} |`,
  );
  const questionRows = questions.map((q, i) => {
    const cells = names.map((n) => ranks[n]![i] ?? "-");
    return `| ${i + 1} | ${q.q} | ${cells.join(" | ")} |`;
  });

  return [
    "# Chunking comparison results",
    "",
    `Model \`${EMBEDDING_MODEL}\`, ${questions.length} questions, top ${TOP_K}. Generated by \`npm run compare\`; do not edit by hand.`,
    "",
    "| Config | Chunks | Avg chars | Hit@1 | Hit@3 | Hit@5 | MRR | Source hit@1 |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...summaryRows,
    "",
    `Best by MRR (ties: Hit@1, then fewer chunks): **${best.name}**`,
    "",
    "Rank of the first relevant chunk per question (`-` = not in the top results):",
    "",
    `| # | Question | ${names.join(" | ")} |`,
    `| --- | --- | ${names.map(() => "---").join(" | ")} |`,
    ...questionRows,
    "",
  ].join("\n");
}
